#!/usr/bin/env python3
"""Compile reviewed JSON into offline Kotlin data; --check prevents committed data drift."""
import argparse
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
TARGET=ROOT/'MuhnPace/src/main/kotlin/com/muhnpacedirect/ResearchDataset.kt'


def generate():
    research=json.loads((ROOT/'metadata/dressrosa-30-37.json').read_text())
    titles=json.loads((ROOT/'metadata/original-anime-titles.json').read_text())['episodes']
    commit=research['artwork_commit']
    assert re.fullmatch('[0-9a-f]{40}',commit or ''), 'Pin the reviewed artwork commit first'
    base=f'https://raw.githubusercontent.com/lincutto/MuhnPaceCloudstream/{commit}/assets/phase4a'
    fields=['collection_id','file_id','source_filename','source_sha256','edit_number','display_title','synopsis',
            'mapping_status','candidate_original_episodes','accepted_original_episodes','scene_confirmed_episodes','title_source_url']
    rows=[dict({k:row[k] for k in fields}, thumbnail_url=base+'/dressrosa/'+Path(row['thumbnail']['file']).name)
          for row in research['entries']]
    encoded=json.dumps(json.dumps(dict(entries=rows,original_titles=titles),ensure_ascii=False,separators=(',',':')),ensure_ascii=False).replace('$','\\$')
    return ('package com.muhnpacedirect\n\n// Generated by scripts/generate_episode_metadata.py; edit the reviewed JSON instead.\n'
            'internal object ResearchDataset {\n'
            f'    const val ARTWORK_BASE = "{base}"\n'
            f'    const val JSON = {encoded}\n'+'}\n')


def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    result=generate()
    if args.check:
        assert TARGET.read_text()==result, 'Regenerate ResearchDataset.kt from the reviewed JSON'
    else: TARGET.write_text(result)
    print('Reviewed episode metadata matches generated Kotlin.' if args.check else 'Generated offline episode metadata.')


if __name__=='__main__': main()
