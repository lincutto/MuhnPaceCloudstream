#!/usr/bin/env python3
"""Compile reviewed JSON into offline Kotlin data; --check prevents committed data drift."""
import argparse
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
TARGET=ROOT/'MuhnPace/src/main/kotlin/com/muhnpacedirect/ResearchDataset.kt'


def generate():
    research=json.loads((ROOT/'metadata/dressrosa-30-37.json').read_text())
    titles=json.loads((ROOT/'metadata/original-anime-titles.json').read_text())['episodes']
    commit=research['artwork_commit']
    assert re.fullmatch('[0-9a-f]{40}',commit or ''), 'Pin the reviewed artwork commit first'
    base=f'https://raw.githubusercontent.com/lincutto/MuhnPaceCloudstream/{commit}/assets/phase4a'
    fields=['collection_id','file_id','source_filename','source_sha256','edit_number','display_title','synopsis',
            'mapping_status','candidate_original_episodes','accepted_original_episodes','scene_confirmed_episodes','title_source_url']
    rows=[]
    for source in sorted((ROOT/'metadata/phase4b').glob('season-*.json')):
        for row in json.loads(source.read_text())['entries']:
            thumb=row['thumbnail']
            assert re.fullmatch('[0-9a-f]{40}',thumb['artwork_commit'])
            assert thumb['file']==f"assets/phase4b/episodes/{row['file_id']}.jpg"
            url=f"https://raw.githubusercontent.com/lincutto/MuhnPaceCloudstream/{thumb['artwork_commit']}/{thumb['file']}"
            rows.append(dict({k:row[k] for k in fields},thumbnail_url=url))
    series=json.loads((ROOT/'metadata/phase4b/series.json').read_text())
    assert re.fullmatch('[0-9a-f]{40}',series['artwork_commit'])
    assert re.fullmatch('[0-9a-f]{40}',series['poster_artwork_commit'])
    series_base=f"https://raw.githubusercontent.com/lincutto/MuhnPaceCloudstream/{series['artwork_commit']}/assets/phase4b/series"
    poster_url=f"https://raw.githubusercontent.com/lincutto/MuhnPaceCloudstream/{series['poster_artwork_commit']}/{series['poster']}"
    serialized=json.dumps(dict(entries=rows,original_titles=titles),ensure_ascii=False,separators=(',',':'))
    # Keep every JVM string constant below 64 KiB and avoid compile-time concatenation.
    chunks=[json.dumps(serialized[i:i+4000],ensure_ascii=False).replace('$','\\$') for i in range(0,len(serialized),4000)]
    encoded=',\n'.join('            '+chunk for chunk in chunks)
    return ('package com.muhnpacedirect\n\n// Generated by scripts/generate_episode_metadata.py; edit the reviewed JSON instead.\n'
            'internal object ResearchDataset {\n'
            f'    const val ARTWORK_BASE = "{base}"\n'
            f'    const val SERIES_ARTWORK_BASE = "{series_base}"\n'
            f'    const val SERIES_POSTER_URL = "{poster_url}"\n'
            f'    val JSON: String by lazy {{ listOf(\n{encoded}\n        ).joinToString("") }}\n'+'}\n')


def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    result=generate()
    if args.check:
        assert TARGET.read_text()==result, 'Regenerate ResearchDataset.kt from the reviewed JSON'
    else: TARGET.write_text(result)
    print('Reviewed episode metadata matches generated Kotlin.' if args.check else 'Generated offline episode metadata.')


if __name__=='__main__': main()
